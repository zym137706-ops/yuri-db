#!/usr/bin/env node
/**
 * Build the slim client-side projections.
 *
 * Why this exists: `data/works.json` is ~4.7 MB. A statically exported site
 * cannot ask a server to filter, so the browser must receive enough data to do
 * it locally — but shipping 4.7 MB would be absurd.
 *
 * Why it runs on Node and imports the REAL lib modules instead of being done in
 * Python: `avg_confidence` must equal what the detail page shows. Deriving it a
 * second time (in another language) is exactly the class of bug this project
 * already hit once — two definitions of "average field confidence" that
 * disagreed about the same record. So we call the same function.
 *
 * Emits:  lib/works-slim.json, lib/anime-slim.json
 */
import { readFileSync, writeFileSync, rmSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const WEB_ROOT = resolve(__dirname, '..');
const REPO_ROOT = resolve(WEB_ROOT, '..');

/* ---------------------------------------------- stage provenance.ts for Node
 * lib/provenance.ts does `import schemaFields from './schema-fields.json'`,
 * which Node rejects without an import attribute. We rewrite that one line to
 * an inline const and give the extensionless relative imports a `.ts` suffix,
 * then import the staged copy. Same technique as scripts/verify-provenance.mjs.
 */
function stageProvenance() {
  const src = join(WEB_ROOT, 'lib', 'provenance.ts');
  const inventory = readFileSync(join(WEB_ROOT, 'lib', 'schema-fields.json'), 'utf8');
  let code = readFileSync(src, 'utf8');
  code = code.replace(
    /^import schemaFields from '\.\/schema-fields\.json';$/m,
    `const schemaFields = ${inventory};`,
  );
  code = code.replace(/from '(\.\/[a-z-]+)';/g, (_m, s) => `from '${s}.ts';`);
  const staged = join(WEB_ROOT, 'lib', '.provenance.staged.ts');
  writeFileSync(staged, code, 'utf8');
  return staged;
}

const staged = stageProvenance();
let averageFieldConfidence;
let policy;
try {
  ({ averageFieldConfidence } = await import(pathToFileURL(staged).href));
  policy = await import(new URL('../lib/policy.ts', import.meta.url).href);
} finally {
  rmSync(staged, { force: true });
}

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

/* ------------------------------------------------------------------ works */
const worksDoc = readJson(join(REPO_ROOT, 'data', 'works.json'));
let totalBytesBefore = Buffer.byteLength(JSON.stringify(worksDoc.works));

const works = worksDoc.works.map((w) => ({
  // Exactly what WorkCard + filterAndSortWorks + workHasZh*Edition read.
  // Deliberately omitted (they dominate the 4.7 MB source):
  //   field_sources, field_confidence  -> replaced by the precomputed avg_confidence
  //   ja_volumes                       -> not needed on the list at all
  //   zh_tw_volumes / zh_cn_volumes    -> replaced by a 1-element placeholder when
  //                                       the real array is non-empty, because
  //                                       workHasZh*Edition only tests `.length > 0`.
  //                                       The boolean therefore stays EXACT.
  id: w.id,
  slug: w.slug,
  title_ja: w.title_ja,
  title_zh_tw: w.title_zh_tw,
  title_zh_cn: w.title_zh_cn,
  title_en: w.title_en,
  title_zh_tw_status: w.title_zh_tw_status,
  title_zh_cn_status: w.title_zh_cn_status,
  media_type: w.media_type,
  serialization_status: w.serialization_status,
  publisher_ja: w.publisher_ja,
  publisher_zh_tw: w.publisher_zh_tw,
  publisher_zh_cn: w.publisher_zh_cn,
  magazine_or_platform: w.magazine_or_platform,
  magazine_or_platform_kind: w.magazine_or_platform_kind,
  authors: w.authors,
  illustrators: w.illustrators,
  genres: w.genres,
  yuri_type: w.yuri_type,
  classification_basis: w.classification_basis,
  anime_status: w.anime_status,
  start_date: w.start_date,
  last_checked: w.last_checked,
  zh_tw_volumes: (w.zh_tw_volumes ?? []).length ? [1] : [],
  zh_cn_volumes: (w.zh_cn_volumes ?? []).length ? [1] : [],
  official_zh_cn: { exists: w.official_zh_cn?.exists === true },
  cover_url: w.cover_url,
  cover_source_url: w.cover_source_url,
  cover_region: w.cover_region,
  cover_display_allowed: w.cover_display_allowed,
  cover_note: w.cover_note,
  volume_count_ja: w.volume_count_ja,
  sources_count: (w.sources ?? []).length,
  // computed with the REAL functions, so the card cannot disagree with the
  // detail page
  avg_confidence: averageFieldConfidence(w),
  has_zh_tw: policy.workHasZhTwEdition(w),
  has_zh_cn: policy.workHasZhCnEdition(w),
}));

const worksSlim = {
  $comment:
    'GENERATED by web/scripts/build-slim.mjs — do not edit. Client-side projection ' +
    'of data/works.json for the statically exported list page. avg_confidence, ' +
    'has_zh_tw and has_zh_cn are computed with the real lib functions so the card ' +
    'and the detail page can never disagree.',
  generated_at: worksDoc.generated_at,
  count: works.length,
  works,
};
writeFileSync(join(WEB_ROOT, 'lib', 'works-slim.json'), JSON.stringify(worksSlim));

/* ------------------------------------------------------------------ anime */
const animeDoc = readJson(join(REPO_ROOT, 'data', 'anime.json'));
const anime = animeDoc.anime.map((a) => ({
  // Exactly what AnimeCard + AnimeFilterPanel + filterAndSortAnime read.
  // `sources_count` stands in for sources[] (the card only shows the count), and
  // episode_duration_min is kept because the card's 集數／時長 summary renders it —
  // dropping it would silently turn a recorded duration into "時長 unknown".
  id: a.id,
  slug: a.slug,
  title_ja: a.title_ja,
  title_romaji: a.title_romaji,
  title_en: a.title_en,
  title_zh_tw: a.title_zh_tw,
  title_zh_cn: a.title_zh_cn,
  format: a.format,
  adaptation_source: a.adaptation_source,
  status: a.status,
  start_date: a.start_date,
  season: a.season,
  season_year: a.season_year,
  episode_count: a.episode_count,
  episode_duration_min: a.episode_duration_min,
  studios: a.studios,
  main_cast: a.main_cast,
  cover_url: a.cover_url,
  cover_source_url: a.cover_source_url,
  related_work_slug: a.related_work_slug,
  yuri_tag_rank: a.yuri_tag_rank,
  country_of_origin: a.country_of_origin,
  average_score: a.average_score,
  popularity: a.popularity,
  sources_count: (a.sources ?? []).length,
}));

const animeSlim = {
  $comment:
    'GENERATED by web/scripts/build-slim.mjs — do not edit. Client-side projection ' +
    'of data/anime.json for the statically exported /anime page; sources_count is the ' +
    'real sources[] length and every filter field is carried verbatim.',
  generated_at: animeDoc.generated_at,
  count: anime.length,
  anime,
};
writeFileSync(join(WEB_ROOT, 'lib', 'anime-slim.json'), JSON.stringify(animeSlim));

// The /anime page runs client-side, so the report it displays must be bundled too.
writeFileSync(
  join(WEB_ROOT, 'lib', 'anime-report.json'),
  readFileSync(join(REPO_ROOT, 'data', 'anime_report.json')),
);

/* ---------------------------------------------------------------- report */
const b = (o) => Buffer.byteLength(JSON.stringify(o));
const fmt = (n) => `${(n / 1024).toFixed(0)} KB`;

/* ------------------------------------------------- served as static assets
 * The projections are published as static files under /data/ and FETCHED by the
 * browser at runtime, instead of being imported into client components.
 * Bundling ~1.2 MB of JSON into the client graph made every prerendered page
 * exceed Next's 60 s per-page budget during `output: 'export'`, and it also
 * duplicated the payload into each page's RSC output. Fetching keeps the HTML
 * tiny and lets the browser cache the data across navigations.
 */
const PUBLIC_DATA = join(WEB_ROOT, 'public', 'data');
mkdirSync(PUBLIC_DATA, { recursive: true });
writeFileSync(join(PUBLIC_DATA, 'works-slim.json'), JSON.stringify(worksSlim));
writeFileSync(join(PUBLIC_DATA, 'anime-slim.json'), JSON.stringify(animeSlim));

console.log('slim projections written:');
console.log(`  works : ${works.length} records  ${fmt(b(worksSlim))}  (from ${fmt(totalBytesBefore)})`);
console.log(`  anime : ${anime.length} records  ${fmt(b(animeSlim))}  (from ${fmt(b(animeDoc))})`);
